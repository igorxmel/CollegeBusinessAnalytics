def build() -> None:
    doc = Document()
    setup(doc)

    para(doc, "Практическая работа № 1", indent=Cm(0),
         align=WD_ALIGN_PARAGRAPH.CENTER)
    para(doc, "Сценарий/гайд глубинного интервью", indent=Cm(0),
         align=WD_ALIGN_PARAGRAPH.CENTER)

    section_heading(doc, "1", "Цель работы")
    blank(doc, 2)
    for text in GOAL:
        para(doc, text)

    section_heading(doc, "2", "Краткая теория")
    blank(doc, 2)
    for text in THEORY:
        para(doc, text)

    section_heading(doc, "3", "Составленный гайд")
    blank(doc, 2)
    for text in GUIDE_NOTE:
        para(doc, text)

    sub_heading(doc, "3.1", "Паспорт интервью")
    para(doc, "Основные договорённости о встрече сведены в таблице 1.")
    table(doc, 1, "Паспорт интервью", ["Параметр", "Значение"], PASSPORT, [4.5, 12.0])

    sub_heading(doc, "3.2", "Структура и тайминг")
    para(doc,
         "Беседа разбита на десять блоков общей длительностью 75 минут. Распределение "
         "времени и преобладающие типы вопросов по каждому блоку приведены в таблице 2.")
    table(doc, 2, "Структура и тайминг интервью",
          ["Подраздел", "Тема", "Минут", "Преобладающие вопросы"],
          TIMING, [2.6, 6.4, 1.8, 5.7])

    table_number = 3
    for block in BLOCKS:
        sub_heading(doc, block["number"], block["title"])
        para(doc, f"Цель блока: {block['goal']}")
        blank(doc, 1)
        if "questions" in block:
            numbered(doc, block["questions"])
        if "items" in block:
            bullets(doc, block["items"])
        blank(doc, 1)
        para(doc, f"Результат блока: {block['result']}")
        for item in block.get("after", []):
            if item[0] == "text":
                blank(doc, 1)
                para(doc, item[1])
            else:
                _, caption, header, rows, widths = item
                table(doc, table_number, caption, header, rows, widths)
                table_number += 1

    sub_heading(doc, "3.13", "Шаблон протокола")
    para(doc,
         "Ответы удобнее записывать сразу в таблицу: так повторяющиеся темы видно на "
         "месте, а требования не теряются между блоками. Состав столбцов протокола "
         "приведён в таблице 5.")
    table(doc, 5, "Столбцы протокола интервью", ["Столбец", "Что в нём"],
          PROTOCOL, [4.0, 12.5])

    section_heading(doc, "4", "Вывод")
    blank(doc, 2)
    for text in CONCLUSION:
        para(doc, text)

    OUT.parent.mkdir(parents=True, exist_ok=True)
    doc.save(OUT)
    print(f"saved: {OUT.name}")


if __name__ == "__main__":
    build()
