# --- rendering helpers ------------------------------------------------------

def setup(doc: Document) -> None:
    section = doc.sections[0]
    # python-docx defaults to US Letter, the college needs A4
    section.page_width = Cm(21)
    section.page_height = Cm(29.7)
    section.left_margin = Cm(3)
    section.right_margin = Cm(1.5)
    section.top_margin = Cm(2)
    section.bottom_margin = Cm(2)

    normal = doc.styles["Normal"]
    normal.font.name = FONT
    normal.font.size = SIZE
    normal.font.bold = False
    normal.font.italic = False
    normal.font.underline = False
    normal.element.rPr.rFonts.set(qn("w:eastAsia"), FONT)

    pf = normal.paragraph_format
    pf.line_spacing = 1.0
    pf.space_before = Pt(0)
    pf.space_after = Pt(0)
    pf.first_line_indent = INDENT
    pf.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY


def para(doc: Document, text: str = "", *, indent=INDENT,
         align=WD_ALIGN_PARAGRAPH.JUSTIFY):
    p = doc.add_paragraph()
    p.paragraph_format.first_line_indent = indent
    p.paragraph_format.alignment = align
    p.paragraph_format.line_spacing = 1.0
    p.paragraph_format.space_before = Pt(0)
    p.paragraph_format.space_after = Pt(0)
    if text:
        run = p.add_run(text)
        run.font.name = FONT
        run.font.size = SIZE
    return p


def blank(doc: Document, count: int = 1) -> None:
    for _ in range(count):
        para(doc)


def page_break(doc: Document) -> None:
    p = para(doc)
    p.add_run().add_break(WD_BREAK.PAGE)


def section_heading(doc: Document, number: str, title: str, *, new_page: bool = False):
    """Раздел: с красной строки, номер, пробел, название.

    Разрыв страницы перед разделом не ставится, хотя свод правил оформления его
    требует. Преподаватель на проверке первой работы сказала убрать: отчёт
    небольшой, и из-за разрывов он расползается на полупустые страницы.
    """
    if new_page:
        page_break(doc)
    else:
        blank(doc, 1)
    para(doc, f"{number} {title}")


def sub_heading(doc: Document, number: str, title: str) -> None:
    """Подраздел: одна пустая строка до, две после."""
    blank(doc, 1)
    para(doc, f"{number} {title}")
    blank(doc, 2)


def bullets(doc: Document, items: list[str]) -> None:
    for item in items:
        para(doc, f"{DASH} {item}")


def numbered(doc: Document, items: list[tuple[str, str]]) -> None:
    for i, (question, kind) in enumerate(items, start=1):
        para(doc, f"{i} {question} ({kind})")


def table(doc: Document, number: int, caption: str, header: list[str],
          rows: list[tuple], widths: list[float]) -> None:
    """Подпись сверху по ширине, таблица шириной в абзац."""
    blank(doc, 1)
    para(doc, f"Таблица {number} {DASH} {caption}")

    t = doc.add_table(rows=1, cols=len(header))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.LEFT
    t.autofit = False

    def fill(cells, values, center: bool) -> None:
        for cell, value, width in zip(cells, values, widths):
            cell.width = Cm(width)
            p = cell.paragraphs[0]
            p.paragraph_format.first_line_indent = Cm(0)
            p.paragraph_format.line_spacing = 1.0
            p.paragraph_format.space_before = Pt(0)
            p.paragraph_format.space_after = Pt(0)
            p.paragraph_format.alignment = (
                WD_ALIGN_PARAGRAPH.CENTER if center else WD_ALIGN_PARAGRAPH.LEFT
            )
            run = p.add_run(str(value))
            run.font.name = FONT
            run.font.size = SIZE

    fill(t.rows[0].cells, header, True)
    for row in rows:
        fill(t.add_row().cells, row, False)

    blank(doc, 1)


