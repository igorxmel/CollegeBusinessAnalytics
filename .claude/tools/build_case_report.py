def dialogue(doc, lines):
    for speaker, text in lines:
        para(doc, f"{speaker}: {text}")


def qa(doc, items):
    for question, answer in items:
        para(doc, f"Вопрос: {question}")
        para(doc, f"Ответ: {answer}")
        blank(doc)


def build():
    doc = Document()
    setup(doc)

    para(doc, "Практическая работа № 2", indent=Cm(0), align=WD_ALIGN_PARAGRAPH.CENTER)
    para(doc, "Глубинное интервью", indent=Cm(0), align=WD_ALIGN_PARAGRAPH.CENTER)

    section_heading(doc, "1", "Цель работы")
    blank(doc, 2)
    for text in GOAL:
        para(doc, text)

    section_heading(doc, "2", "Краткая теория")
    blank(doc, 2)
    for text in THEORY:
        para(doc, text)
    table(doc, 1, "Сравнение форматов исследования", COMPARE_HEADER, COMPARE,
          [3.6, 4.6, 4.1, 4.2])

    section_heading(doc, "3", "Составленный кейс")
    blank(doc, 2)
    for text in CASE_LEAD:
        para(doc, text)

    sub_heading(doc, "3.1", "Приветствие и вступление")
    dialogue(doc, GREETING)

    for number, title, items in BLOCKS:
        sub_heading(doc, number, title)
        qa(doc, items)

    sub_heading(doc, "3.10", "Завершение беседы")
    dialogue(doc, CLOSING)

    section_heading(doc, "4", "Вывод")
    blank(doc, 2)
    for text in CONCLUSION:
        para(doc, text)

    OUT.parent.mkdir(parents=True, exist_ok=True)
    doc.save(OUT)
    print(f"saved: {OUT.name}")


if __name__ == "__main__":
    build()
